using System.Text;
using SiJenggo.Game;
using SiJenggo.Game.Data;

namespace SiJenggo.Balance;

/// <summary>Turns raw run results into the markdown balance report.</summary>
internal static class Report
{
    private static string Sec(double ticks) => ticks < 0 || double.IsNaN(ticks) ? "–" : (ticks / 60.0).ToString("0");

    private static string Pct(double v) => double.IsNaN(v) ? "–" : (v * 100).ToString("0") + "%";

    private static double Median(IEnumerable<double> values)
    {
        var sorted = values.Where(v => v >= 0).Order().ToArray();
        if (sorted.Length == 0)
        {
            return double.NaN;
        }

        int mid = sorted.Length / 2;
        return sorted.Length % 2 == 1 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
    }

    private static string BossName(int chapter) => Bosses.Get(Chapters.Get(chapter).Boss).Name.En;

    public static string Build(IReadOnlyList<RunResult> results, Options options, TimeSpan elapsed, long simTicks)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Balance sweep report");
        sb.AppendLine();
        sb.AppendLine("Generated by `tools/SiJenggo.Balance` (see [BALANCE.md](BALANCE.md)). Players are driven either by the");
        sb.AppendLine("**skilled bot** (`SkilledBot`: steps out of hazards, dodges about 60% of the attacks it can react to after a");
        sb.AppendLine("12-tick delay) or by the **in-game companion AI** (`PlayerLoadout.IsAi`: never dodges, blocks or avoids hazards).");
        sb.AppendLine("All fighters use base stats (no levels, skills or gear) and 3 lives; Deaths counts every life lost, so a loss");
        sb.AppendLine("is 4 per player. The co-op partner is the next character in roster order (Jenggo+Bima, Bima+Rani, Rani+Ucup,");
        sb.AppendLine("Ucup+Jenggo). Bots are not humans: read these numbers as relative signals, not as the experience a player will have.");
        sb.AppendLine();
        sb.AppendLine($"- Sessions: {results.Count} ({options.Seeds} seeds per configuration), {simTicks / 60.0 / 3600.0:0.0} simulated hours");
        sb.AppendLine($"- Wall time: {elapsed.TotalSeconds:0.0} s on {options.Threads} threads");
        sb.AppendLine($"- Caps: boss arena {options.BossCapSeconds} s, full chapter {options.ChapterCapSeconds} s (a capped run counts as a loss in Win%)");
        sb.AppendLine("- Times are medians in seconds over the runs that reached that point; fight time and phase times only count wins.");
        sb.AppendLine("- Damage is total damage taken by all players per run (mean); the share columns split it by source:");
        sb.AppendLine("  the boss itself, other enemies (minions, shadow clones, wave enemies), and hazards (boss mechanics, phase shockwaves, ambient).");
        sb.AppendLine();

        foreach (var (kind, bot) in options.Kinds.SelectMany(k => options.Bots.Select(b => (k, b))))
        {
            var subset = results.Where(r => r.Scenario.Kind == kind && r.Scenario.Bot == bot).ToList();
            if (subset.Count == 0)
            {
                continue;
            }

            string who = bot == BotKind.Skilled ? "skilled bot" : "in-game companion AI";
            sb.AppendLine(kind == RunKind.Boss ? $"## Boss arenas, {who} (fresh players, boss only)" : $"## Full chapters, {who} (waves, then the boss)");
            sb.AppendLine();
            foreach (bool coop in new[] { false, true })
            {
                sb.AppendLine(coop ? "### Two players (co-op)" : "### One player (solo)");
                sb.AppendLine();
                sb.AppendLine("| Ch | Boss | Diff | Win% | Clear s | Fight s | P1 s | P2 s | P3 s | Boss HP left (losses) | Dmg taken | Deaths | Boss % | Enemies % | Hazards % |");
                sb.AppendLine("|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
                foreach (var group in subset.Where(r => r.Scenario.Coop == coop)
                    .GroupBy(r => (r.Scenario.Chapter, r.Scenario.Difficulty))
                    .OrderBy(g => g.Key.Chapter).ThenBy(g => g.Key.Difficulty))
                {
                    AppendRow(sb, $"{group.Key.Chapter + 1} | {BossName(group.Key.Chapter)} | {group.Key.Difficulty}", group.ToList());
                }

                sb.AppendLine();
            }

            sb.AppendLine("### Per character (solo, all chapters)");
            sb.AppendLine();
            sb.AppendLine("| Character | Diff | Win% | Clear s | Fight s | P1 s | P2 s | P3 s | Boss HP left (losses) | Dmg taken | Deaths | Boss % | Enemies % | Hazards % |");
            sb.AppendLine("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
            foreach (var group in subset.Where(r => !r.Scenario.Coop)
                .GroupBy(r => (r.Scenario.Character, r.Scenario.Difficulty))
                .OrderBy(g => g.Key.Character).ThenBy(g => g.Key.Difficulty))
            {
                AppendRow(sb, $"{Characters.Get(group.Key.Character).Name.En} | {group.Key.Difficulty}", group.ToList());
            }

            sb.AppendLine();
            sb.AppendLine("### Win% per chapter x character (solo / co-op, Normal)");
            sb.AppendLine();
            sb.Append("| Ch | Boss |");
            foreach (var c in Characters.All)
            {
                sb.Append($" {c.Name.En} |");
            }

            sb.AppendLine();
            sb.Append("|---:|---|");
            foreach (var _ in Characters.All)
            {
                sb.Append("---:|");
            }

            sb.AppendLine();
            foreach (int chapter in subset.Select(r => r.Scenario.Chapter).Distinct().Order())
            {
                sb.Append($"| {chapter + 1} | {BossName(chapter)} |");
                foreach (var c in Characters.All)
                {
                    var solo = subset.Where(r => r.Scenario.Chapter == chapter && r.Scenario.Character == c.Id && r.Scenario.Difficulty == Difficulty.Normal && !r.Scenario.Coop).ToList();
                    var duo = subset.Where(r => r.Scenario.Chapter == chapter && r.Scenario.Character == c.Id && r.Scenario.Difficulty == Difficulty.Normal && r.Scenario.Coop).ToList();
                    sb.Append($" {WinRate(solo)} / {WinRate(duo)} |");
                }

                sb.AppendLine();
            }

            sb.AppendLine();
            sb.AppendLine("### Boss damage by move (mean per run, solo, Normal)");
            sb.AppendLine();
            sb.AppendLine("| Ch | Boss | Moves (damage dealt to players) |");
            sb.AppendLine("|---:|---|---|");
            foreach (int chapter in subset.Select(r => r.Scenario.Chapter).Distinct().Order())
            {
                var runs = subset.Where(r => r.Scenario.Chapter == chapter && r.Scenario.Difficulty == Difficulty.Normal && !r.Scenario.Coop).ToList();
                var moves = runs.SelectMany(r => r.BossMoveDamage).GroupBy(kv => kv.Key)
                    .Select(g => (Move: g.Key, Damage: g.Sum(kv => kv.Value) / Math.Max(1, runs.Count)))
                    .OrderByDescending(m => m.Damage)
                    .Select(m => $"{(m.Move == 0 ? "projectile" : Moves.Get(new MoveId((ushort)m.Move)).Key)} {m.Damage:0}");
                sb.AppendLine($"| {chapter + 1} | {BossName(chapter)} | {string.Join(", ", moves)} |");
            }

            sb.AppendLine();
            sb.AppendLine("### Hazard damage by kind (mean per run, solo, Normal)");
            sb.AppendLine();
            var kinds = Enum.GetValues<SiJenggo.Game.Components.HazardKind>();
            sb.Append("| Ch | Boss |");
            foreach (var k in kinds)
            {
                sb.Append($" {k} |");
            }

            sb.AppendLine(" Other |");
            sb.Append("|---:|---|");
            for (int k = 0; k <= kinds.Length; k++)
            {
                sb.Append("---:|");
            }

            sb.AppendLine();
            foreach (int chapter in subset.Select(r => r.Scenario.Chapter).Distinct().Order())
            {
                var runs = subset.Where(r => r.Scenario.Chapter == chapter && r.Scenario.Difficulty == Difficulty.Normal && !r.Scenario.Coop).ToList();
                sb.Append($"| {chapter + 1} | {BossName(chapter)} |");
                for (int k = 0; k <= kinds.Length; k++)
                {
                    double v = runs.Count == 0 ? 0 : runs.Average(r => r.HazardDamage[k]);
                    sb.Append(v < 0.5 ? " · |" : $" {v:0} |");
                }

                sb.AppendLine();
            }

            sb.AppendLine();
        }

        return sb.ToString();
    }

    private static string WinRate(List<RunResult> runs) => runs.Count == 0 ? "–" : Pct(runs.Count(r => r.Outcome == Outcome.Win) / (double)runs.Count);

    private static void AppendRow(StringBuilder sb, string label, List<RunResult> runs)
    {
        var wins = runs.Where(r => r.Outcome == Outcome.Win).ToList();
        var losses = runs.Where(r => r.Outcome != Outcome.Win).ToList();
        double damage = runs.Average(r => r.DamageTaken);
        double total = runs.Sum(r => r.DamageTaken);
        double boss = total <= 0 ? double.NaN : runs.Sum(r => r.DamageFromBoss) / total;
        double enemies = total <= 0 ? double.NaN : runs.Sum(r => r.DamageFromEnemies) / total;
        double hazards = total <= 0 ? double.NaN : runs.Sum(r => r.DamageFromHazards) / total;
        string hpLeft = losses.Count == 0 ? "–" : Pct(losses.Average(r => r.BossHealthLeft));
        sb.AppendLine($"| {label} | {WinRate(runs)} | {Sec(Median(wins.Select(r => (double)r.Ticks)))} | {Sec(Median(wins.Select(r => (double)r.BossFightTicks)))} | " +
                      $"{Sec(Median(wins.Select(r => (double)r.PhaseTicks(0))))} | {Sec(Median(wins.Select(r => (double)r.PhaseTicks(1))))} | {Sec(Median(wins.Select(r => (double)r.PhaseTicks(2))))} | " +
                      $"{hpLeft} | {damage:0} | {runs.Average(r => r.LivesUsed):0.0} | {Pct(boss)} | {Pct(enemies)} | {Pct(hazards)} |");
    }

    public static string Csv(IReadOnlyList<RunResult> results)
    {
        var sb = new StringBuilder();
        sb.AppendLine("kind,bot,chapter,character,partner,coop,difficulty,seed,outcome,ticks,boss_start,p1_end,p2_end,p3_end,boss_hp_left,damage,dmg_boss,dmg_enemies,dmg_hazards,lives_used,downs,revives");
        foreach (var r in results)
        {
            var s = r.Scenario;
            sb.AppendLine($"{s.Kind},{s.Bot},{s.Chapter},{s.Character},{(s.Coop ? s.Partner.ToString() : "")},{s.Coop},{s.Difficulty},{s.Seed},{r.Outcome},{r.Ticks},{r.BossStartTick}," +
                          $"{r.PhaseEndTick[0]},{r.PhaseEndTick[1]},{r.PhaseEndTick[2]},{r.BossHealthLeft:0.000},{r.DamageTaken:0},{r.DamageFromBoss:0},{r.DamageFromEnemies:0},{r.DamageFromHazards:0},{r.LivesUsed},{r.Downs},{r.Revives}");
        }

        return sb.ToString();
    }
}
